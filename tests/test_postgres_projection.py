from schedule_kit.tasks.maintenance import cleanup_execution_records

pytestmark = [
    pytest.mark.postgres,
    pytest.mark.django_db,
    pytest.mark.skipif(
        connection.vendor != "postgresql", reason="requires --ds=tests.pg_settings"
    ),
]

SHARED = {
    "WRITE_MAIN_EXECUTION_RECORDS": True,
    "EXECUTION_SOURCE": "example-service",
    "PENDING_TIMEOUT_HOURS": 1,
}

# Column types and constraints as in oivsion360 (celery_skdl up to 0041).
LEGACY_DDL = """
CREATE TABLE celery_skdl_executionrecord (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_title varchar(255) NOT NULL,
    task_function varchar(255) NOT NULL,
    task_id integer NOT NULL,
    task_created_by_id integer NOT NULL,
    result varchar(8) NOT NULL,
    start_time timestamp with time zone NOT NULL,
    end_time timestamp with time zone NOT NULL,
    message text NOT NULL,
    task_model varchar(255) NOT NULL,
    periodic_task_id integer NULL
        REFERENCES django_celery_beat_periodictask(id) DEFERRABLE INITIALLY DEFERRED
)"""
# celery_skdl.0042_executionrecord_message_i18n
I18N_DDL = """
ALTER TABLE celery_skdl_executionrecord
    ADD COLUMN message_code varchar(100) NULL,
    ADD COLUMN message_i18n jsonb NULL,
    ADD COLUMN message_params jsonb NULL"""

REPORT_SENT = ExecutionMessage(
    "example.report.sent", "Task raised %(exception)s", {"exception": "中文 OK"}
)


@pytest.fixture
def rule(user):
    return AlertRuleTask.objects.create(
        title="PG " + uuid.uuid4().hex,
        execution_cycle="*/5 * * * *",
        created_by=user,
        cpu_threshold=80,
        target_host="pg",
        notify_email="pg@example.test",
    )


@pytest.fixture(autouse=True)
def fresh_column_cache():
    transports.reset_main_columns_cache()
    yield
    transports.reset_main_columns_cache()


def create_main_table(i18n=True):
    with connection.cursor() as c:
        c.execute(LEGACY_DDL)
        if i18n:
            c.execute(I18N_DDL)


def task(rule, message):
    def run(scheduler_id, record_id=None):
        return rule, None if message is None else True, message or "waiting"

    return recorded_task(
        name="pg_" + uuid.uuid4().hex,
        scheduler_model=AlertRuleTask,
        require_record=message is None,
    )(run)


def main_rows(i18n=True):
    columns = "result, task_model, message"
    if i18n:
        columns += (
            ", message_code, message_params, message_i18n, jsonb_typeof(message_i18n)"
        )
    with connection.cursor() as c:
        c.execute(f"SELECT {columns} FROM celery_skdl_executionrecord ORDER BY id")
        rows = c.fetchall()
    if not i18n:
        return rows
    # Django's PostgreSQL backend leaves jsonb undecoded on raw cursors.
    decode = lambda value: None if value is None else json.loads(value)  # noqa: E731
    return [row[:4] + (decode(row[4]), decode(row[5])) + row[6:] for row in rows]


@override_settings(CELERY_SCHEDULER=SHARED)
def test_execution_message_reaches_0042_main_table(rule):
    create_main_table()
    record_id = task(rule, REPORT_SENT).run(rule.pk)
    local = ExecutionRecord.objects.get(pk=record_id)
    assert local.main_synced_at is not None
    assert main_rows() == [
        (
            "success",
            "example-service:example.AlertRuleTask",
            "Task raised 中文 OK",
            "example.report.sent",
            {"exception": "中文 OK"},
            {"en": "Task raised 中文 OK", "zh-hant": "任務發生例外：中文 OK"},
            "object",
        )
    ]
    assert (local.message_params, local.message_i18n) == main_rows()[0][4:6]


@override_settings(CELERY_SCHEDULER=SHARED)
def test_plain_text_leaves_i18n_columns_null(rule):
    create_main_table()
    task(rule, "plain").run(rule.pk)
    assert main_rows() == [
        ("success", "example-service:example.AlertRuleTask", "plain")
        + (None,) * 4
    ]


@override_settings(CELERY_SCHEDULER=SHARED)
def test_legacy_main_table_degrades_once(rule, caplog):
    create_main_table(i18n=False)
    with caplog.at_level(logging.WARNING):
        first = task(rule, REPORT_SENT).run(rule.pk)
        second = task(rule, REPORT_SENT).run(rule.pk)
    assert main_rows(i18n=False) == [
        ("success", "example-service:example.AlertRuleTask", "Task raised 中文 OK")
    ] * 2
    assert not ExecutionRecord.objects.filter(
        pk__in=[first, second], main_synced_at=None
    ).exists()
    assert sum("celery_skdl.0042" in r.getMessage() for r in caplog.records) == 1


@override_settings(CELERY_SCHEDULER=SHARED)
def test_missing_table_is_retried_by_maintenance(rule):
    # The failed introspection must not poison the transaction or the cache.
    record_id = task(rule, REPORT_SENT).run(rule.pk)
    assert ExecutionRecord.objects.get(pk=record_id).main_synced_at is None
    create_main_table()
    cleanup_execution_records.run()
    cleanup_execution_records.run()
    assert len(main_rows()) == 1
    assert main_rows()[0][3] == "example.report.sent"
    assert ExecutionRecord.objects.get(pk=record_id).main_synced_at is not None


@override_settings(CELERY_SCHEDULER=SHARED)
def test_timeout_and_exception_messages_in_both_languages(rule):
    create_main_table()
    pending_id = task(rule, None).run(rule.pk)
    ExecutionRecord.objects.filter(pk=pending_id).update(
        occurred_at=timezone.now() - timedelta(hours=2)
    )
    cleanup_execution_records.run()

    def boom(scheduler_id, record_id=None):
        raise ValueError("password=secret")

    with pytest.raises(ValueError):
        recorded_task(name="pg_" + uuid.uuid4().hex, scheduler_model=AlertRuleTask)(
            boom
        ).run(rule.pk)

    rows = main_rows()
    assert [(r[0], r[3]) for r in rows] == [
        ("fail", "schedule_kit.pending_timeout"),
        ("fail", "schedule_kit.task_raised"),
    ]
    assert rows[0][5] == {
        "en": "timeout: pending exceeded configured limit",
        "zh-hant": "逾時：pending 狀態超過設定的時限",
    }
    assert rows[1][5] == {
        "en": TASK_RAISED.with_params(exception="ValueError").render("en"),
        "zh-hant": "任務發生例外：ValueError",
    }
    assert "secret" not in repr(rows)


@override_settings(CELERY_SCHEDULER=SHARED)
def test_maintenance_leaves_other_sources_alone(rule):
    create_main_table()
    old = timezone.now() - timedelta(days=90)
    other = ExecutionRecord.objects.create(
        task_model="other-service:example.AlertRuleTask",
        task_id=rule.pk,
        task_created_by_id=rule.created_by_id,
        status="pending",
        occurred_at=old,
    )
    other_unsynced = ExecutionRecord.objects.create(
        task_model="other-service:example.AlertRuleTask",
        task_id=rule.pk,
        task_created_by_id=rule.created_by_id,
        status="success",
        occurred_at=old,
        end_time=old,
    )
    cleanup_execution_records.run()
    assert ExecutionRecord.objects.get(pk=other.pk).status == "pending"
    assert ExecutionRecord.objects.filter(pk=other_unsynced.pk).exists()
    assert main_rows() == []


def test_migration_0005_columns_on_postgres():
    with connection.cursor() as c:
        description = {
            col.name: col
            for col in connection.introspection.get_table_description(
                c, "schedule_kit_executionrecord"
            )
        }
        c.execute(
            "SELECT column_name, data_type FROM information_schema.columns "
            "WHERE table_name = 'schedule_kit_executionrecord' "
            "AND column_name IN ('message_code', 'message_params', 'message_i18n')"
        )
        types = dict(c.fetchall())
    assert types == {
        "message_code": "character varying",
        "message_params": "jsonb",
        "message_i18n": "jsonb",
    }
    assert all(description[name].null_ok for name in types)
